"""Checker ablation: how much do recalculation, liveness and preservation rules add?

For every case (canonical seed 0) three outputs are graded:

* ``reference``: a correct solution (should pass),
* ``failure``: the committed failure artifact (should fail),
* ``noop``: the untouched input, i.e. an agent that did nothing (should fail).

Each output is graded by three graders:

* ``failbook``: every rule, values recalculated by LibreOffice (the real grader),
* ``values-only``: only the *content* and *value* rules, still recalculated; this is
  what a typical "compare the numbers with the expected answer" check does,
* ``cached-values``: the same rules, but reading the values stored in the file
  without recalculating, as a script using ``openpyxl.load_workbook(data_only=True)``
  would.

This measures the graders on Failbook's own reconstructed failures. It says
nothing about how often real agents fail; see docs/DATASHEET.md for the
selection caveats.
"""

from __future__ import annotations

import datetime as dt
import json
import shutil
import tempfile
from pathlib import Path
from typing import Any

from . import __version__
from .case import Case
from .engine import default_engine
from .grade import grade

GRADERS = {
    "failbook": {"kinds": None, "cached": False},
    "values-only": {"kinds": ["content", "value"], "cached": False},
    "cached-values": {"kinds": ["content", "value"], "cached": True},
}
EXPECTED = {"reference": "pass", "failure": "fail", "noop": "fail"}


def run_ablation(cases: list[Case], *, engine=None) -> dict[str, Any]:
    engine = engine or default_engine()
    rows = []
    for case in cases:
        with tempfile.TemporaryDirectory(prefix=f"failbook-ablation-{case.id}-") as tmp:
            tmp = Path(tmp)
            inputs = tmp / "input"
            meta = case.inputs_for(0, inputs, engine=engine)
            outputs = {"noop": inputs, "failure": case.failure_dir}
            ref = tmp / "reference"
            shutil.copytree(inputs, ref)
            case.solve("reference", ref, meta)
            outputs["reference"] = ref
            for label, workdir in outputs.items():
                for gname, cfg in GRADERS.items():
                    rep = grade(case, workdir, 0, engine=engine, input_dir=inputs, kinds=cfg["kinds"], cached=cfg["cached"])
                    rows.append({
                        "case": case.id,
                        "output": label,
                        "grader": gname,
                        "verdict": rep.verdict,
                        "expected": EXPECTED[label],
                        "failed_rules": [r.id for r in rep.rules if r.status == "fail"],
                        "inconclusive_rules": [r.id for r in rep.rules if r.status == "inconclusive"],
                    })
    return {
        "generated_at": dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds"),
        "failbook_version": __version__,
        "engine": engine.describe(),
        "seed": 0,
        "graders": {k: {"kinds": v["kinds"] or "all", "recalculated": not v["cached"]} for k, v in GRADERS.items()},
        "rows": rows,
    }


def _verdict(rows, case, output, grader):
    for r in rows:
        if r["case"] == case and r["output"] == output and r["grader"] == grader:
            return r
    return None


def render(data: dict[str, Any], cases: list[Case]) -> str:
    rows = data["rows"]
    names = list(GRADERS)

    def count(output, grader, verdict):
        return sum(1 for r in rows if r["output"] == output and r["grader"] == grader and r["verdict"] == verdict)

    n = len(cases)
    lines = [
        "# Checker ablation",
        "",
        "<!-- generated by `failbook ablation`; do not edit by hand -->",
        "",
        f"Generated {data['generated_at'][:10]} with failbook {data['failbook_version']} and {data['engine']}, "
        f"seed {data['seed']}, {n} cases. Reproduce with `failbook ablation`.",
        "",
        "**Question.** Do Failbook's recalculation, liveness (perturb an input, check results follow) and "
        "preservation rules catch failures that a plain value comparison misses, without rejecting correct work?",
        "",
        "**Method.** For every case, three outputs are graded by three graders. *reference* is a correct "
        "solution, *failure* the committed failure artifact, *noop* the untouched input (an agent that did "
        "nothing). *failbook* is the real grader. *values-only* keeps only the rules that compare the requested "
        "content and recalculated values. *cached-values* uses the same rules but reads the numbers stored in the "
        "file, as `openpyxl.load_workbook(data_only=True)` does, without recalculating.",
        "",
        "**Caveats.** The failures are Failbook's own reconstructions, chosen because they are subtle. The counts "
        "describe the graders on this collection, not how often agents fail. The *cached-values* grader \"catches\" "
        "failures mostly for the wrong reason: files written by openpyxl (the failure artifacts included) store no "
        "formula results at all, so it rejects almost every scripted output, correct or not.",
        "",
        "| Grader | Failures caught | Correct solutions accepted | Empty attempts caught | Inconclusive |",
        "|---|---|---|---|---|",
    ]
    for g in names:
        inc = sum(1 for r in rows if r["grader"] == g and r["verdict"] == "inconclusive")
        lines.append(
            f"| `{g}` | {count('failure', g, 'fail')} / {n} | {count('reference', g, 'pass')} / {n} | "
            f"{count('noop', g, 'fail')} / {n} | {inc} |"
        )
    lines += [
        "",
        "## Per case",
        "",
        "✅ the grader gave the right verdict, ❌ the wrong one, ❔ inconclusive.",
        "",
        "| Case | " + " | ".join(f"{g}: failure / reference / noop" for g in names) + " |",
        "|---|" + "---|" * len(names),
    ]
    for c in cases:
        cells = []
        for g in names:
            marks = []
            for out in ("failure", "reference", "noop"):
                r = _verdict(rows, c.id, out, g)
                if r is None:
                    marks.append("·")
                elif r["verdict"] == "inconclusive":
                    marks.append("❔")
                else:
                    marks.append("✅" if r["verdict"] == r["expected"] else "❌")
            cells.append(" ".join(marks))
        lines.append(f"| [{c.id}](../../cases/{c.dir.name}/) {c.title} | " + " | ".join(cells) + " |")
    missed = [c for c in cases if (_verdict(rows, c.id, "failure", "values-only") or {}).get("verdict") == "pass"]
    if missed:
        lines += ["", "## Failures that only the full grader catches", ""]
        for c in missed:
            r = _verdict(rows, c.id, "failure", "failbook")
            lines.append(f"- **{c.id}** {c.title}: caught by `{', '.join(r['failed_rules'])}`.")
    rejected = [c for c in cases if (_verdict(rows, c.id, "reference", "cached-values") or {}).get("verdict") != "pass"]
    if rejected:
        lines += [
            "",
            "## Correct solutions rejected by the cached-values grader",
            "",
            "openpyxl writes formulas without their results, so a grader that reads stored values sees empty "
            "cells where the correct formulas are:",
            "",
        ]
        for c in rejected:
            r = _verdict(rows, c.id, "reference", "cached-values")
            lines.append(f"- **{c.id}**: {r['verdict']} (`{', '.join(r['failed_rules'] or r['inconclusive_rules'])}`)")
    lines.append("")
    return "\n".join(lines)


def write_ablation(cases: list[Case], out_dir: Path) -> Path:
    data = run_ablation(cases)
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "checker-ablation.json").write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    path = out_dir / "checker-ablation.md"
    path.write_text(render(data, cases), encoding="utf-8")
    return path


# -- the fix's self-check ----------------------------------------------------------------
def run_audit_eval(cases: list[Case], *, engine=None) -> dict[str, Any]:
    """Run the case-agnostic audit (shipped in the spreadsheet-verify-skill fix) on every
    failure artifact and on every correct solution, comparing each with its original input."""
    from .audit import audit

    engine = engine or default_engine()
    rows = []
    for case in cases:
        with tempfile.TemporaryDirectory(prefix=f"failbook-audit-{case.id}-") as tmp:
            tmp = Path(tmp)
            inputs = tmp / "input"
            meta = case.inputs_for(0, inputs, engine=engine)
            outputs = {"failure": case.failure_dir}
            for kind in ["reference", *case.alternatives()]:
                work = tmp / kind
                shutil.copytree(inputs, work)
                case.solve(kind, work, meta)
                outputs[kind] = work
            for label, workdir in outputs.items():
                for name in case.outputs:
                    found = audit(workdir / name, inputs / name)
                    rows.append({
                        "case": case.id,
                        "output": label,
                        "errors": [f.__dict__ for f in found if f.level == "error"],
                        "warnings": [f.__dict__ for f in found if f.level == "warning"],
                    })
    return {
        "generated_at": dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds"),
        "failbook_version": __version__,
        "engine": engine.describe(),
        "rows": rows,
    }


def render_audit(data: dict[str, Any], cases: list[Case]) -> str:
    rows = data["rows"]
    fails = [r for r in rows if r["output"] == "failure"]
    goods = [r for r in rows if r["output"] != "failure"]
    flagged = [r for r in fails if r["errors"] or r["warnings"]]
    flagged_err = [r for r in fails if r["errors"]]
    good_err = [r for r in goods if r["errors"]]
    good_warn = [r for r in goods if r["warnings"] and not r["errors"]]
    lines = [
        "# Does the fix's self-check catch the failures?",
        "",
        "<!-- generated by `failbook audit-eval`; do not edit by hand -->",
        "",
        f"Generated {data['generated_at'][:10]} with failbook {data['failbook_version']} and {data['engine']}. "
        "Reproduce with `failbook audit-eval`.",
        "",
        "The [spreadsheet-verify-skill](../../fixes/spreadsheet-verify-skill/) fix asks the agent to run "
        "`scripts/audit_xlsx.py --before <original> <edited>` before reporting success. The script knows nothing "
        "about the task. This page measures it on Failbook's failure artifacts (should be flagged) and on the "
        "correct solutions, references and alternatives (should be clean). *Error* findings are near-certain "
        "mistakes; *warnings* ask for a manual check.",
        "",
        "**Read with care.** The checks were written with these 15 failure artifacts in view, so the table measures "
        "coverage of known patterns, not how well the script generalises to new failures. It also does not show "
        "that agents do better with the fix: that needs recorded runs with and without it, and until then it is a "
        "hypothesis.",
        "",
        "| Output | Total | Flagged (error or warning) | Flagged with an error | Clean |",
        "|---|---|---|---|---|",
        f"| failure artifacts | {len(fails)} | {len(flagged)} | {len(flagged_err)} | {len(fails) - len(flagged)} |",
        f"| correct solutions | {len(goods)} | {len(good_err) + len(good_warn)} | {len(good_err)} | "
        f"{len(goods) - len(good_err) - len(good_warn)} |",
        "",
        "## Per case",
        "",
        "| Case | Failure artifact | Correct solutions |",
        "|---|---|---|",
    ]

    def summary(r):
        items = [f"**{f['check']}**" for f in r["errors"]] + [f"{f['check']} (warning)" for f in r["warnings"]]
        return ", ".join(dict.fromkeys(items)) or "clean"

    for c in cases:
        f = next(r for r in rows if r["case"] == c.id and r["output"] == "failure")
        g = [f"{r['output']}: {summary(r)}" for r in rows if r["case"] == c.id and r["output"] != "failure"]
        lines.append(f"| [{c.id}](../../cases/{c.dir.name}/) {c.title} | {summary(f)} | {'; '.join(g)} |")
    missed = [r["case"] for r in fails if not (r["errors"] or r["warnings"])]
    if missed:
        lines += ["", "## Not caught", "",
                  "These failures leave no generic symptom; only the task's requirements reveal them, so the skill's "
                  "written checklist (and the agent following it) has to cover them: " + ", ".join(missed) + "."]
    if good_err or good_warn:
        lines += ["", "## Findings on correct solutions", ""]
        for r in good_err + good_warn:
            for f in r["errors"] + r["warnings"]:
                lines.append(f"- {r['case']} {r['output']}: [{f['level']}] {f['check']} at {f['where']}: {f['message']}")
    lines.append("")
    return "\n".join(lines)


def write_audit_eval(cases: list[Case], out_dir: Path) -> Path:
    data = run_audit_eval(cases)
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "fix-self-check.json").write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    path = out_dir / "fix-self-check.md"
    path.write_text(render_audit(data, cases), encoding="utf-8")
    return path
