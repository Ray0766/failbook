"""Generated documentation: one README per case, plus the case index in the top-level READMEs.

Each case README follows the evidence chain: task and inputs -> expected result ->
observed failure (with the rule-by-rule grading of the failure artifact) ->
explanation -> how to reproduce -> fixes and recorded retests.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

from .case import Case, all_cases, repo_root

MARK = "<!-- generated by `failbook docs` from case.yaml, task.md, case.py and results/; do not edit by hand -->"
INDEX_START, INDEX_END = "<!-- cases:start -->", "<!-- cases:end -->"
REPO_URL = "https://github.com/Ray0766/failbook"

KIND_LABEL = {
    "en": {"content": "content", "value": "value", "live": "live", "preserve": "no collateral damage", "structure": "structure"},
    "zh": {"content": "内容", "value": "数值", "live": "实时性", "preserve": "无连带破坏", "structure": "结构"},
}
CATEGORY_LABEL = {
    "en": {"model": "model/agent failure", "tool": "tool failure", "environment": "environment error",
           "evaluator": "evaluator error", "undetermined": "undetermined"},
    "zh": {"model": "模型/智能体失败", "tool": "工具失败", "environment": "环境错误", "evaluator": "评测器错误",
           "undetermined": "尚未确定"},
}


def failure_grades(case: Case) -> dict[str, dict]:
    path = case.failure_dir / "grade.json"
    if not path.is_file():
        return {}
    data = json.loads(path.read_text(encoding="utf-8"))
    return {r["id"]: r for r in data.get("rules", [])}


def case_results(case: Case) -> list[dict]:
    from .report import load_results

    root = repo_root()
    if root is None:
        return []
    results, _ = load_results(root / "results")
    return sorted((r for r in results if r["case"] == case.id), key=lambda r: r["started_at"])


def _quote(text: str) -> str:
    return "\n".join("> " + line if line else ">" for line in text.strip().splitlines())


def _shift_headings(markdown: str) -> str:
    return re.sub(r"^(#+) ", lambda m: "#" * (len(m.group(1)) + 2) + " ", markdown, flags=re.M)


def _esc(text: str) -> str:
    return (text or "").replace("|", "\\|").replace("\n", " ")


def rules_table(case: Case, lang: str) -> str:
    grades = failure_grades(case)
    if lang == "zh":
        head = "| 规则 | 类型 | 检查内容 | 失败产物的判定 |\n|---|---|---|---|"
    else:
        head = "| Rule | Kind | What it checks | Failure artifact |\n|---|---|---|---|"
    rows = []
    for r in case.rules:
        g = grades.get(r.id, {})
        status = g.get("status", "?")
        detail = _esc(g.get("detail") or "")
        cell = (f"**FAIL**: {detail}" if detail else "**FAIL**") if status == "fail" else status
        title = _esc(r.title_zh if lang == "zh" and r.title_zh else r.title)
        rows.append(f"| `{r.id}` | {KIND_LABEL[lang][r.kind]} | {title} | {cell} |")
    return head + "\n" + "\n".join(rows)


def runs_table(case: Case, lang: str) -> str:
    runs = case_results(case)
    if not runs:
        if lang == "zh":
            return ("尚无复测记录。按上面的命令运行后，把 `results/` 下生成的文件提交 PR；"
                    "每次运行追加一个新文件，不覆盖旧记录。")
        return ("No recorded runs yet. Run one of the commands above and open a pull request with the file it "
                "writes under `results/`. Every run is a new file; existing records are never overwritten.")
    head = ("| 日期 | 案例版本 | 智能体 | 模型 | 修复 | 运行状态 | 判定 | 未通过的规则 |" if lang == "zh"
            else "| Date | Case version | Agent | Model | Fix | Run status | Verdict | Rules not passed |")
    lines = [head, "|---|---|---|---|---|---|---|---|"]
    for r in runs:
        bad = ", ".join(f"`{x['id']}`" for x in r["rules"] if x["status"] != "pass") or "—"
        agent = r["agent"]["name"] + (f" {r['agent'].get('version')}" if r["agent"].get("version") else "")
        version = f"v{r['case_version']}" + ("" if r["case_version"] == case.version else
                                             (" (旧版)" if lang == "zh" else " (older)"))
        lines.append(
            f"| {r['started_at'][:10]} | {version} | {_esc(agent)} | {_esc(r.get('model') or '—')} | "
            f"{r.get('fix') or '—'} | {r.get('run_status', '—')} | **{r['verdict']}** | {bad} |"
        )
    return "\n".join(lines)


def _links(kinds: list[str]) -> str:
    links = [f"[`{k}.py`]({k}.py)" for k in kinds]
    return links[0] if len(links) == 1 else ", ".join(links[:-1]) + " and " + links[-1]


def _validation(case: Case) -> str:
    """What `failbook verify` proves for this case, naming the solution files it uses."""
    valid = ["reference", *case.alternatives()]
    wrong = case.failure_fixtures()
    their = "its" if len(valid) == 1 else "their"
    text = (f"{_links(valid)} must pass, also after LibreOffice opens and re-saves {their} output; "
            "the failure must fail on the rules listed in `case.yaml`")
    if wrong:
        text += (f"; {_links(wrong)} ({'another wrong solution' if len(wrong) == 1 else 'other wrong solutions'}) "
                 "must be graded fail")
    return text + "; and the untouched input must fail."


