def index_table(cases: list[Case], lang: str = "en") -> str:
    if lang == "zh":
        head = "| 编号 | 可观察到的失败 | 难度 | 失败产物被哪些规则抓到 |\n|---|---|---|---|"
    else:
        head = "| ID | Observable failure | Difficulty | Caught by |\n|---|---|---|---|"
    rows = []
    for c in cases:
        title = c.title_zh if lang == "zh" else c.title
        kinds = {r.id: r.kind for r in c.rules}
        caught = sorted({KIND_LABEL[lang][kinds[g]] for g, v in failure_grades(c).items()
                         if v.get("status") == "fail" and g in kinds})
        rows.append(f"| [{c.id}](cases/{c.dir.name}/) | {title} | {c.spec.get('difficulty', '')} | {', '.join(caught)} |")
    return head + "\n" + "\n".join(rows)


def _replace_block(text: str, block: str) -> str:
    if INDEX_START not in text or INDEX_END not in text:
        return text
    before, rest = text.split(INDEX_START, 1)
    _, after = rest.split(INDEX_END, 1)
    return f"{before}{INDEX_START}\n{block}\n{INDEX_END}{after}"


def write_all_docs(check: bool = False) -> list[Path]:
    """Write (or, with ``check``, compare) every generated document. Returns paths that differ."""
    cases = all_cases()
    changed: list[Path] = []
    targets: dict[Path, str] = {c.dir / "README.md": case_readme(c) for c in cases}
    root = repo_root()
    if root:
        # The fix ships a copy of the audit script; keep it identical to the package's.
        audit_src = Path(__file__).with_name("audit.py").read_text(encoding="utf-8")
        targets[root / "fixes" / "spreadsheet-verify-skill" / "skill" / "scripts" / "audit_xlsx.py"] = audit_src
        for name, lang in (("README.md", "en"), ("README.zh-CN.md", "zh")):
            path = root / name
            if path.is_file():
                targets[path] = _replace_block(path.read_text(encoding="utf-8"), index_table(cases, lang))
        from .report import render_markdown, load_results

        results, _ = load_results(root / "results")
        targets[root / "RESULTS.md"] = render_markdown(results)
    for path, content in targets.items():
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current != content:
            changed.append(path)
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8")
    return changed
